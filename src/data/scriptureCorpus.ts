// Helper Navigation & Query Functions
export function getVersesByScripture(scriptureId: string): DetailedVerse[] {
  return Object.values(VERSES_DATABASE).filter((v) => v.scriptureId === scriptureId);
}

export function getVersesByScriptureAndChapter(scriptureId: string, chapterNum: number): DetailedVerse[] {
  return Object.values(VERSES_DATABASE).filter(
    (v) => v.scriptureId === scriptureId && v.chapterNum === chapterNum
  );
}

export function getAdjacentVerses(currentVerseId: string): {
  prevVerse?: DetailedVerse;
  nextVerse?: DetailedVerse;
  allScriptureVerses: DetailedVerse[];
} {
  const current = VERSES_DATABASE[currentVerseId];
  if (!current) {
    return { allScriptureVerses: Object.values(VERSES_DATABASE) };
  }

  const scriptureVerses = getVersesByScripture(current.scriptureId);
  const idx = scriptureVerses.findIndex((v) => v.id === currentVerseId);

  return {
    prevVerse: idx > 0 ? scriptureVerses[idx - 1] : undefined,
    nextVerse: idx >= 0 && idx < scriptureVerses.length - 1 ? scriptureVerses[idx + 1] : undefined,
    allScriptureVerses: scriptureVerses,
  };
}

// Daily Shloka Calendar Rotation Engine
export function getDailyShlokaForDate(date: Date = new Date()): DetailedVerse {
  const dayOfYear = Math.floor(
    (date.getTime() - new Date(date.getFullYear(), 0, 0).getTime()) / 1000 / 60 / 60 / 24
  );
  const verseKeys = Object.keys(VERSES_DATABASE);
  const selectedKey = verseKeys[Math.abs(dayOfYear) % verseKeys.length];
  return VERSES_DATABASE[selectedKey] || VERSES_DATABASE["bg_2_47"];
}
